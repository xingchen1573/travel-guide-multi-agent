"""Route data contracts shared by Codex and LangGraph."""

from __future__ import annotations

from typing import Literal, Optional

from pydantic import BaseModel, Field


# ---------- route_plan.json ----------


class SourceRef(BaseModel):
    platform: str
    author: str = ""
    doc_id: str = ""
    chunk_id: str = ""  # Exact supporting fragment; empty keeps historical document-level references valid.
    source_url: str = ""
    # global_core / project_supplement / project_evidence; working_note is never a SourceRef.
    scope: str = "global_core"


class EvidenceClaimEvidenceSnapshot(BaseModel):
    """事实写入时固化的证据摘录，不依赖后续日志或素材状态。"""

    source: SourceRef
    excerpt: str = ""
    observed_at: str = ""
    source_kind: Literal["material", "project_web", "runtime_web", "amap", "unknown"] = "unknown"


class EvidenceClaim(BaseModel):
    """产物中一条可独立验收的事实及其生成时来源。"""

    claim_id: str = ""  # Deterministically generated by the write tool; model input is ignored.
    target_path: str = "notes"  # For example notes / recommendation / warning / highlight.
    subject: str = ""
    claim_text: str
    claim_type: str = "other"
    support_mode: Literal[
        "direct", "amap", "derived", "estimate", "user_constraint", "unverified"
    ] = "direct"
    claimed_entities: list[str] = Field(default_factory=list)
    evidence_refs: list[SourceRef] = Field(default_factory=list)
    evidence_snapshots: list[EvidenceClaimEvidenceSnapshot] = Field(default_factory=list)
    derived_from: list[str] = Field(default_factory=list)
    provenance_mode: Literal["live", "reconstructed"] = "live"


class RouteClaimEvidenceSnapshot(EvidenceClaimEvidenceSnapshot):
    """兼容旧导入名；新模块统一使用EvidenceClaimEvidenceSnapshot。"""


class RouteClaim(EvidenceClaim):
    """路线事实的兼容类名。"""


class RoutePoi(BaseModel):
    """route_plan.json v2：pois从字符串列表升级为对象列表，见docs/WORKSPACE.md第2.1节。"""

    name: str
    brief: str = ""
    needs_detail: bool = False
    needs_detail_reason: str = ""


class RouteDay(BaseModel):
    day: int
    city: str
    area: str = ""
    pois: list[RoutePoi] = Field(default_factory=list)
    notes: str = ""
    sources: list[SourceRef] = Field(
        default_factory=list,
        description="兼容性天级来源并集；新路线由claims[].evidence_refs自动汇总，不由模型独立维护",
    )
    claims: list[RouteClaim] = Field(
        default_factory=list,
        description="本日关键事实到具体证据的映射；sources由这些事实引用取并集兼容生成",
    )
    citation_status: str = "passed"
    # Populated only when citation_status=force_finalized so consumers can mark exact entities.
    missing_entities: list[str] = Field(default_factory=list)


class RoutePlan(BaseModel):
    version: int = 2
    days: list[RouteDay] = Field(default_factory=list)
    amap_verified: bool = False
    created_at: str = ""
    updated_at: str = ""


# ---------- route_entities.json / route_execution.json ----------


class RouteGeoPoint(BaseModel):
    lng: float
    lat: float


class RouteEntityCandidate(BaseModel):
    provider_id: str = ""
    provider_name: str = ""
    type: str = ""
    address: str = ""
    province: str = ""
    city: str = ""
    district: str = ""
    location: Optional[RouteGeoPoint] = None
    score: Optional[float] = None
    score_reasons: list[str] = Field(default_factory=list)
    rejected_reason: str = ""


class RouteEntityResolution(BaseModel):
    day: int
    poi_index: int
    formal_name: str
    provider_query: str = ""
    provider: str = "amap"
    provider_id: str = ""
    provider_name: str = ""
    type: str = ""
    address: str = ""
    province: str = ""
    city: str = ""
    district: str = ""
    location: Optional[RouteGeoPoint] = None
    candidates: list[RouteEntityCandidate] = Field(default_factory=list)
    selection_reason: list[str] = Field(default_factory=list)
    confidence: float = 0.0
    status: Literal[
        "resolved",
        "ambiguous",
        "unresolved",
        "requires_human_confirmation",
        "stale",
    ] = "unresolved"
    resolved_at: str = ""


class RouteEntities(BaseModel):
    schema_version: str = "route-entities-v1"
    route_plan_structure_hash: str = ""
    entities: list[RouteEntityResolution] = Field(default_factory=list)
    updated_at: str = ""


class RouteLegSegment(BaseModel):
    from_name: str
    to_name: str
    mode: Literal[
        "driving",
        "taxi",
        "public_transit",
        "scenic_shuttle",
        "cable_car",
        "walking",
        "rail",
        "mixed",
        "unknown",
    ]
    duration_minutes: Optional[int] = None
    distance_km: Optional[float] = None
    notes: str = ""


class RouteLeg(BaseModel):
    day: int
    from_poi_index: int
    to_poi_index: int
    from_name: str = ""
    to_name: str = ""
    transport_mode: Literal[
        "driving",
        "taxi",
        "public_transit",
        "scenic_shuttle",
        "cable_car",
        "walking",
        "rail",
        "mixed",
        "unknown",
    ] = "unknown"
    segments: list[RouteLegSegment] = Field(default_factory=list)
    planned_departure: str = ""
    planned_arrival: str = ""
    duration_minutes: Optional[int] = None
    distance_km: Optional[float] = None
    notes: str = ""


class RouteOperationalCommitment(BaseModel):
    commitment_id: str = ""
    action: str
    category: str
    target_day: int
    target_poi_index: int
    target_name: str = ""
    planned_on_day: Optional[int] = None
    applies_to_day: Optional[int] = None
    objects: list[str] = Field(default_factory=list)
    status: Literal["planned", "completed", "partial", "cancelled", "unknown"] = "planned"
    source_claim_ids: list[str] = Field(default_factory=list)
    notes: str = ""


class RouteExecutionPlan(BaseModel):
    schema_version: str = "route-execution-v1"
    route_plan_structure_hash: str = ""
    route_legs: list[RouteLeg] = Field(default_factory=list)
    operational_commitments: list[RouteOperationalCommitment] = Field(default_factory=list)
    updated_at: str = ""


# ---------- route_feasibility.json ----------


class RouteFeasibilityEvidence(BaseModel):
    title: str = ""
    url: str = ""
    excerpt: str = ""
    source_type: Literal["official", "government", "map", "verified_web", "ugc", "unknown"] = "unknown"
    observed_at: str = ""


class RouteFeasibilityCheck(BaseModel):
    check_id: str
    day: int
    target: str
    target_type: Literal["poi", "road", "schedule"]
    category: str
    status: Literal["passed", "warning", "blocked", "unknown"]
    summary: str = ""
    evidence: list[RouteFeasibilityEvidence] = Field(default_factory=list)
    checked_at: str = ""
    applicable_date: str = ""
    requires_structure_change: bool = False
    suggested_action: str = ""
    technical_error: Optional[str] = None
    technical_error_class: str = ""
    validation_attempt: int = 1
    judge_provider: str = ""
    judge_model: str = ""
    requested_categories: list[str] = Field(default_factory=list)
    returned_categories: list[str] = Field(default_factory=list)
    stream_completed: Optional[bool] = None
    entity_kind: str = "unknown"
    route_role: str = "unknown"
    check_profile: str = "unknown_conservative"
    coverage_status: Literal["covered", "partial", "missing", "not_applicable", "unknown"] = "unknown"
    matched_route_claim_ids: list[str] = Field(default_factory=list)
    matched_commitment_ids: list[str] = Field(default_factory=list)
    missing_requirement_codes: list[str] = Field(default_factory=list)


class RouteFeasibilityDateContext(BaseModel):
    precision: Literal["exact", "month", "season", "unknown"] = "unknown"
    start_date: Optional[str] = None
    end_date: Optional[str] = None
    source_text: str = ""
    query_baseline_date: str = ""


class RouteFeasibilityReport(BaseModel):
    schema_version: str = "route-feasibility-v1"
    route_plan_updated_at: str = ""
    route_plan_structure_hash: str = ""
    requirements_date_context: RouteFeasibilityDateContext = Field(default_factory=RouteFeasibilityDateContext)
    overall_status: Literal["passed", "warning", "blocked", "unknown"] = "unknown"
    checks: list[RouteFeasibilityCheck] = Field(default_factory=list)
    force_finalized: bool = False
    created_at: str = ""

